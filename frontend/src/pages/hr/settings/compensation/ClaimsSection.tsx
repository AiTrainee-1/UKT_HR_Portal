import { Link } from "wouter";
import {
  ArrowUpRight,
  CalendarCheck2,
  CheckCircle2,
  ClipboardCheck,
  Hand,
  Search,
  Wallet,
  Workflow,
} from "lucide-react";
import { Input } from "@/components/ui/input";
import { cn } from "@/lib/utils";
import { SettingBlock, SettingsSection } from "../kit/SettingBlock";
import { COMPENSATION_SECTIONS, compensationText } from "../CompensationTab.meta";
import { prettyDate } from "./form";
import { notes, Problem, type SectionProps } from "./ui";
import { leavePath, otPath } from "@/pages/hr/compensation/routes";

const block = (id: string) => ({ id, ...compensationText(id) });

/** The five steps every claim goes through, as the employee and HR see them. */
const STEPS = [
  {
    icon: Search,
    title: "Detected",
    text: "The system finds what was earned from attendance: overtime (Type 1 allowance, Type 2 credit), Sunday or holiday work, and work on a birthday.",
  },
  {
    icon: Hand,
    title: "Claimed",
    text: "The employee claims it in the mobile app or on the web, or HR claims it for them on the Compensation page.",
  },
  {
    icon: ClipboardCheck,
    title: "Approved by the HOD",
    text: "The claim goes to the employee's Department Head. Only an approved claim gives anything; a rejected one gives nothing.",
  },
  {
    icon: Wallet,
    title: "Balance",
    text: "An approved credit (Type 2, Sunday or holiday work, birthday) is added to the compensation balance. A Type 1 allowance is applied to the next working day instead.",
  },
  {
    icon: CalendarCheck2,
    title: "Used on another day",
    text: "The employee asks to use the balance on a working day (0.25 to 1.00 shift); the Department Head approves and that day is paid without punches.",
  },
] as const;

/**
 * How compensation is claimed (2026-11-19): one workflow for every kind, from detection to using the balance, and the date
 * it started. The server set the date once; HR may move it LATER only (never earlier than `claimsMinFrom`, never blank), so
 * days before it keep the old rules and nothing already judged changes. It is saved with the rest of the tab. A View-only
 * role sees the date as text.
 */
export function ClaimsSection({ claimsFrom, claimsMinFrom, draft, patch, readOnly, validation }: SectionProps) {
  const from = claimsFrom ? prettyDate(claimsFrom) : null;
  const error = validation.claimsFrom;
  const moved = !!claimsFrom && draft.claimsFrom !== claimsFrom && draft.claimsFrom !== "" && !error;
  return (
    <SettingsSection
      id="compensation-claims"
      icon={Workflow}
      title={COMPENSATION_SECTIONS.claims}
      purpose="Overtime credits, Sunday and holiday work and birthday credits are not given automatically: they are claimed, approved by the Department Head, added to the balance and used later. Staff only."
      usedBy={[
        { label: "Compensation", to: leavePath("holiday-work", "claims") },
        { label: "Approvals" },
        { label: "Employee apps" },
      ]}
      testId="compensation-claims"
    >
      <SettingBlock
        {...block("claims-workflow")}
        affects={[
          {
            where: "Compensation - OT Detection",
            what: "each detected record shows whether it is claimable, waiting for the HOD, approved or rejected, with Claim for employee",
            to: otPath("type-1"),
          },
          {
            where: "Compensation - Claims, Balance and Credits",
            what: "every claim of every kind, the balance it builds (earned, used, waiting, available) and the ledger entry it made",
            to: leavePath("holiday-work", "claims"),
          },
          {
            where: "Approvals",
            what: "the Department Head approves or rejects each claim and each request to use the balance",
          },
          { where: "Employee apps", what: "My Compensation: claim, use the balance, and follow every claim" },
        ]}
        note={notes(
          <>
            Who approves is set in{" "}
            <Link
              href="/hr/user-management?tab=approvals"
              className="inline-flex items-center gap-0.5 font-semibold underline"
              data-testid="link-claims-approval-workflow"
            >
              User Management - Approval Workflow Control
              <ArrowUpRight size={11} />
            </Link>{" "}
            (Compensation claims: the Department Head with the compensation approval right).
          </>,
          "Payroll is never regenerated by a claim: a payslip changes only when HR generates that month again.",
        )}
      >
        <ol
          className="grid gap-2 sm:grid-cols-2"
          data-testid="claims-steps"
          aria-label="The claim workflow, step by step"
        >
          {STEPS.map((step, i) => {
            const Icon = step.icon;
            return (
              <li
                key={step.title}
                className="flex min-w-0 flex-col gap-1.5 rounded-xl border border-slate-200 bg-white p-3"
              >
                <span className="flex items-center gap-1.5 text-[12px] font-bold text-slate-900">
                  <span className="rounded-lg bg-indigo-50 p-1.5 text-indigo-700" aria-hidden="true">
                    <Icon size={14} />
                  </span>
                  <span>
                    {i + 1}. {step.title}
                  </span>
                </span>
                <span className="text-[12px] leading-snug text-slate-600">{step.text}</span>
              </li>
            );
          })}
        </ol>
      </SettingBlock>

      <SettingBlock
        {...block("claims-from")}
        labelFor={from && !readOnly ? "compensation-claims-from" : undefined}
        defaultText="The day the claim workflow was installed"
        affects={[
          {
            where: "Staff Attendance",
            what: "days before it keep the old rules (automatic Type 1 allowance and birthday leave) even when they are worked out again",
            to: "/hr/attendance/staff",
          },
          {
            where: "Compensation - OT Detection",
            what: "records before it are shown with their old meaning; from it they are claimed",
            to: otPath("type-1"),
          },
        ]}
        note="Set by the server when the claim workflow was installed. It can only be moved later, never back or cleared, so nothing already judged or paid changes."
      >
        {from && !readOnly ? (
          <div className="space-y-1.5" data-testid="claims-from">
            <div className="flex flex-wrap items-center gap-2">
              <Input
                id="compensation-claims-from"
                type="date"
                value={draft.claimsFrom}
                min={claimsMinFrom || undefined}
                aria-invalid={error ? true : undefined}
                aria-describedby="compensation-claims-from-help"
                onChange={(e) => patch({ claimsFrom: e.target.value })}
                className={cn("w-44", error && "border-red-400")}
              />
              {moved && (
                <span className="text-xs text-slate-600" data-testid="claims-from-moved">
                  Saved as {from}: from {prettyDate(draft.claimsFrom)} once you save.
                </span>
              )}
            </div>
            <p id="compensation-claims-from-help" className="text-xs text-slate-500" data-testid="claims-from-help">
              Can only move later: days before it keep the old automatic rules.
            </p>
            {error && <Problem testId="claims-from-error">{error}</Problem>}
          </div>
        ) : (
          <div
            className="flex flex-wrap items-center gap-2 rounded-xl border border-slate-200 bg-slate-50 px-3 py-2.5"
            data-testid="claims-from"
          >
            <CheckCircle2 size={16} className="shrink-0 text-emerald-600" aria-hidden="true" />
            {from ? (
              <span className="text-sm text-slate-800">
                Claims apply from <strong data-testid="claims-from-date">{from}</strong>. View only.
              </span>
            ) : (
              <span className="text-sm text-slate-700">
                Not reported by the server yet: the date is set when the claim workflow is installed.
              </span>
            )}
          </div>
        )}
      </SettingBlock>
    </SettingsSection>
  );
}
