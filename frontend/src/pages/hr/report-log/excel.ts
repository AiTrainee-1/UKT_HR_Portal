// The Excel file of a paper-style list: the company block on top, the salmon title bar, then one block per unit with its label
// (HO, U-1 ...) in the left gutter, a blank row between blocks, and the footer. Built from the same SheetSpec as the sheet on
// screen, so the file and the picture never differ.

import type { Workbook } from "exceljs";
import { addTitleBlock, allBorders, fileSafe, newWorkbook, solidFill, styleHeaderCell } from "@/lib/exportUtils";
import { unitCounts, totalRows } from "./logic";
import type { SheetSpec } from "./sheets";

export type ExcelContext = {
  company: string;
  branchLabel: string;
  logoDataUrl?: string | null;
};

const argb = (hex: string) => `FF${hex.replace("#", "").toUpperCase()}`;
const BLACK = argb("#000000");

/** The workbook of one list (not yet saved). Row 5 is the header row, as it always was on the Daily report. */
export function buildSheetWorkbook(spec: SheetSpec, ctx: ExcelContext): Workbook {
  const wb = newWorkbook();
  const ws = wb.addWorksheet("Report");
  const totalCols = spec.columns.length + 1;
  ws.columns = [{ width: 7 }, ...spec.columns.map((c) => ({ width: c.chars }))];

  addTitleBlock(wb, ws, {
    totalCols,
    company: ctx.company,
    branchLabel: ctx.branchLabel,
    title: spec.title,
    titleFill: argb(spec.titleFill),
    logoDataUrl: ctx.logoDataUrl,
  });

  const headerRow = ws.getRow(5);
  spec.columns.forEach((col, i) => {
    const cell = headerRow.getCell(i + 2);
    cell.value = col.header;
    styleHeaderCell(cell, {
      fill: "FFFFFFFF",
      color: col.headerColor ? argb(col.headerColor) : BLACK,
      border: allBorders("thin", BLACK),
    });
  });

  let rowIdx = 6;
  spec.blocks.forEach((block, blockIndex) => {
    if (blockIndex > 0) rowIdx += 1; // the blank row between two blocks
    block.rows.forEach((row, i) => {
      const r = ws.getRow(rowIdx);
      if (i === 0) {
        const gutter = r.getCell(1);
        gutter.value = block.label;
        gutter.font = { bold: true, size: 12 };
        gutter.alignment = { horizontal: "center", vertical: "middle" };
        gutter.border = allBorders("thin", BLACK);
      }
      spec.columns.forEach((col, c) => {
        const out = col.cell(row, i);
        const cell = r.getCell(c + 2);
        cell.value = col.key === "sno" ? i + 1 : out.text;
        cell.alignment = { horizontal: col.align, vertical: "middle" };
        cell.border = allBorders("thin", BLACK);
        if (out.fill) cell.fill = solidFill(argb(out.fill));
        if (out.bold) cell.font = { bold: true };
      });
      rowIdx += 1;
    });
  });

  const footer = ws.getCell(`A${rowIdx + 1}`);
  footer.value = `Total ${totalRows(spec.blocks)}${spec.blocks.length > 1 ? ` (${unitCounts(spec.blocks)})` : ""} · Generated by ${ctx.company} HRMS`;
  footer.font = { italic: true, size: 9, color: { argb: "FF999999" } };
  return wb;
}

export const sheetFileName = (spec: SheetSpec) => `${fileSafe(spec.title)}.xlsx`;
